"""The WirePlumber hook that keeps a speaker filter off the headphone jack.

A smart filter picks its target by node properties, and WirePlumber exposes
no property for a sink's active port. So on a card whose speakers and
headphone jack are two ports of one sink (plain HDA with no UCM profile,
issue #73) the filter keeps processing after headphones are plugged in.

The hook is a WirePlumber 0.5 Lua script plus the conf fragment that loads
it. It watches the target sink's active route, and while that route's
``port.type`` is anything but ``speaker`` it sets ``filter.smart.disabled``
on the filter in the ``filters`` metadata, WirePlumber's own runtime
override (its "Smart Filters" policy page). Streams then link straight to
the sink. It acts only on filters whose conf carries `MARKER`, so the script
is the same text on every machine and nobody else's filter is touched.

Both files are text constants because ``lib/`` holds only Python
(``tests/test_packaging.py``). Stdlib-only: the entry script decides when to
install, from ``lib.hardware.sinks.non_speaker_ports``.
"""

from __future__ import annotations

from pathlib import Path

from lib import xdg

# The capture-node property `lib.pipewire.conf.format_conf` emits and
# `SCRIPT` looks for.
MARKER = "speaker-tuning.speaker-port-only"

HEADER_MARK = "Generated by ee_to_pipewire.py"
_URL = "https://github.com/antoinecellerier/speaker-tuning-to-easyeffects"

# In a WirePlumber ``scripts/`` directory, which is also how the fragment
# names it. Flat, so removing it leaves no folder of ours behind.
SCRIPT_NAME = "speaker-tuning-port.lua"
FRAGMENT_NAME = "90-speaker-tuning-port.conf"
FEATURE = "hooks.speaker-tuning.port"

# The profile requires only `LOADER`, a virtual component that *wants* the
# script. A script named `required` directly would stop WirePlumber, and with
# it all audio, if it failed to load; one named `optional` is never loaded
# (WirePlumber's "Components & Profiles" page). A wanted feature is tried, and
# its failure is logged and survived. `hooks.` in the feature name is what
# makes WirePlumber's stock components.rules load the script before its event
# source starts.
LOADER = "speaker-tuning.port"

FRAGMENT = f"""\
# {HEADER_MARK} — see
# {_URL}
#
# Loads the hook that bypasses a speaker filter while its target sink's
# active port is not a speaker port (headphones on the same sink).

wireplumber.components = [
  {{
    name = {SCRIPT_NAME}, type = script/lua
    provides = {FEATURE}
    requires = [ metadata.filters ]
  }}
  {{
    type = virtual, provides = {LOADER}
    wants = [ {FEATURE} ]
  }}
]

wireplumber.profiles = {{
  main = {{
    {LOADER} = required
  }}
}}
"""

SCRIPT = f"""\
-- {HEADER_MARK} — see
-- {_URL}
--
-- Bypasses a speaker filter while its target sink's active port is not a
-- speaker port: headphones plugged into a jack that shares the speakers'
-- sink. Acts only on smart filters carrying the property
-- {MARKER} = true.

cutils = require ("common-utils")
log = Log.open_topic ("s-speaker-tuning")

local MARKER = "{MARKER}"
local KEY = "filter.smart.disabled"

-- A route's info is a flat list: count, then key and value in turn.
local function portType (route)
  local info = route.info
  if type (info) ~= "table" then
    return nil
  end
  for i = 2, #info - 1, 2 do
    if info [i] == "port.type" then
      return info [i + 1]
    end
  end
  return nil
end

-- Whether the card offers a speaker-typed port on this sink at all. Without
-- one there is nothing to tell the speakers by.
local function hasSpeakerPort (device, cpd)
  for p in device:iterate_params ("EnumRoute") do
    local route = cutils.parseParam (p, "EnumRoute")
    if route and route.direction == "Output"
        and portType (route) == "speaker" then
      for _, d in ipairs (route.devices or {{}}) do
        if d == cpd then
          return true
        end
      end
    end
  end
  return false
end

-- The port.type of the sink's active output route, nil when it can't be told
-- or when the sink has no speaker port to compare it with.
local function activePortType (sink, device_om)
  local cpd = tonumber (sink.properties ["card.profile.device"])
  local device_id = sink.properties ["device.id"]
  if cpd == nil or device_id == nil then
    return nil
  end
  local device = device_om:lookup {{
    Constraint {{ "bound-id", "=", device_id, type = "gobject" }},
  }}
  if device == nil or not hasSpeakerPort (device, cpd) then
    return nil
  end
  for p in device:iterate_params ("Route") do
    local route = cutils.parseParam (p, "Route")
    if route and route.direction == "Output" and route.device == cpd then
      return portType (route)
    end
  end
  return nil
end

local function targetName (filter)
  local str = filter.properties ["filter.smart.target"]
  if str == nil then
    return nil
  end
  local json = Json.Raw (str)
  if not json:is_object () then
    return nil
  end
  return json:parse () ["node.name"]
end

-- The node.name the default metadata names as the output streams follow.
local function selectedSink (metadata_om)
  local metadata = metadata_om:lookup {{
    Constraint {{ "metadata.name", "=", "default" }},
  }}
  local str = metadata and metadata:find (0, "default.audio.sink")
  if str == nil then
    return nil
  end
  local json = Json.Raw (str)
  if not json:is_object () then
    return nil
  end
  return json:parse ().name
end

local function evaluate (source)
  local node_om = source:call ("get-object-manager", "node")
  local device_om = source:call ("get-object-manager", "device")
  local metadata_om = source:call ("get-object-manager", "metadata")
  local metadata = metadata_om:lookup {{
    Constraint {{ "metadata.name", "=", "filters" }},
  }}
  if metadata == nil then
    return
  end
  local selected = selectedSink (metadata_om)

  for filter in node_om:iterate () do
    local marked = filter.properties [MARKER]
    local target = marked and cutils.parseBool (marked) and targetName (filter)
    if target then
      -- An unreadable port leaves the filter on, as without this hook.
      local port = nil
      for sink in node_om:iterate () do
        if sink.properties ["node.name"] == target then
          port = activePortType (sink, device_om)
          break
        end
      end
      -- A filter that is itself the selected output stays on: streams
      -- target it directly, and bypassed it would feed them nowhere.
      local disable = port ~= nil and port ~= "speaker"
          and filter.properties ["node.name"] ~= selected
      local id = filter ["bound-id"]
      local current = metadata:find (id, KEY)
      if disable and current ~= "true" then
        log:info (filter, "bypassing: " .. target .. " is on a "
            .. port .. " port")
        metadata:set (id, KEY, "Spa:String:JSON", "true")
      elseif not disable and current ~= nil then
        log:info (filter, "applying: " .. target .. " is on its speaker port")
        metadata:set (id, KEY, nil, nil)
      end
    end
  end
end

SimpleEventHook {{
  name = "speaker-tuning/route-changed",
  interests = {{
    EventInterest {{
      Constraint {{ "event.type", "=", "device-params-changed" }},
      Constraint {{ "event.subject.param-id", "=", "Route" }},
    }},
  }},
  execute = function (event)
    evaluate (event:get_source ())
  end
}}:register ()

SimpleEventHook {{
  name = "speaker-tuning/default-changed",
  interests = {{
    EventInterest {{
      Constraint {{ "event.type", "=", "metadata-changed" }},
      Constraint {{ "metadata.name", "=", "default" }},
      Constraint {{ "event.subject.key", "=", "default.audio.sink" }},
    }},
  }},
  execute = function (event)
    evaluate (event:get_source ())
  end
}}:register ()

-- The filter and its target each arrive as an Audio/Sink node.
SimpleEventHook {{
  name = "speaker-tuning/sink-added",
  interests = {{
    EventInterest {{
      Constraint {{ "event.type", "=", "node-added" }},
      Constraint {{ "media.class", "=", "Audio/Sink" }},
    }},
  }},
  execute = function (event)
    evaluate (event:get_source ())
  end
}}:register ()
"""


# WirePlumber loads a custom `hooks.*` script before its event source only
# from this version on (upstream commit fae96655, read at each 0.5.x tag).
# Older 0.5 releases can start the script too late for the events of a
# session's first moments. Not observed: no such WirePlumber was run.
ORDERED_LOAD = (0, 5, 6)


def paths(staging: Path | None = None) -> tuple[Path, Path]:
    """Where the (script, fragment) pair goes.

    ``None`` is the live install: the per-user directories WirePlumber reads
    (its "Locations" page). A ``staging`` directory, the folder of a conf
    written with ``--output``, gets the same layout under ``wireplumber/``
    for whoever installs the files from there."""
    if staging is None:
        return (xdg.data_home() / "wireplumber" / "scripts" / SCRIPT_NAME,
                xdg.config_home() / "wireplumber" / "wireplumber.conf.d"
                / FRAGMENT_NAME)
    root = staging / "wireplumber"
    return (root / "scripts" / SCRIPT_NAME,
            root / "wireplumber.conf.d" / FRAGMENT_NAME)


def is_ours(path: Path) -> bool:
    """Whether ``path`` is a hook file this tool wrote, by its first line."""
    try:
        with path.open(errors="replace") as fh:
            return HEADER_MARK in fh.readline()
    except OSError:
        return False


def installed(staging: Path | None = None) -> bool:
    """Whether both hook files are in place."""
    return all(is_ours(p) for p in paths(staging))


def foreign(staging: Path | None = None) -> list[Path]:
    """Files in the hook's places that this tool didn't write, which
    `write` refuses to replace."""
    return [p for p in paths(staging) if p.exists() and not is_ours(p)]


def write(staging: Path | None = None) -> tuple[Path, Path]:
    """Write both files and return their paths.

    Rewrites its own files unasked: the text is the same for every chain, so
    a second chain's install must not need ``--force`` for it. The caller
    checks `foreign` first."""
    script, fragment = paths(staging)
    for path, text in ((script, SCRIPT), (fragment, FRAGMENT)):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return script, fragment
